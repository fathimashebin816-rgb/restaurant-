using SiluzzCafe.DesignParser.Models;

namespace SiluzzCafe.DesignParser.Generators;

/// <summary>
/// Generates C# constant classes from design tokens for compile-time access
/// </summary>
public static class DesignTokenGenerator
{
    /// <summary>
    /// Generates a C# file with color constants
    /// </summary>
    public static string GenerateColorConstants(DesignSystem design)
    {
        var colors = design.Colors;
        var sb = new System.Text.StringBuilder();

        sb.AppendLine("// <auto-generated />");
        sb.AppendLine($"// Generated from {design.Name} design system");
        sb.AppendLine("#nullable enable");
        sb.AppendLine();
        sb.AppendLine("namespace SiluzzCafe.DesignTokens;");
        sb.AppendLine();
        sb.AppendLine("/// <summary>");
        sb.AppendLine("/// Siluzz Cafe color design tokens");
        sb.AppendLine("/// </summary>");
        sb.AppendLine("public static class Colors");
        sb.AppendLine("{");

        var colorProperties = colors.GetType().GetProperties();
        foreach (var prop in colorProperties)
        {
            var value = prop.GetValue(colors) as string ?? string.Empty;
            var constantName = ToConstantName(prop.Name);
            var description = GetColorDescription(prop.Name);
            
            sb.AppendLine($"    /// <summary>{description}</summary>");
            sb.AppendLine($"    public const string {constantName} = \"{value}\";");
            sb.AppendLine();
        }

        sb.AppendLine("}");
        return sb.ToString();
    }

    /// <summary>
    /// Generates a C# file with typography constants
    /// </summary>
    public static string GenerateTypographyConstants(DesignSystem design)
    {
        var typography = design.Typography;
        var sb = new System.Text.StringBuilder();

        sb.AppendLine("// <auto-generated />");
        sb.AppendLine($"// Generated from {design.Name} design system");
        sb.AppendLine("#nullable enable");
        sb.AppendLine();
        sb.AppendLine("namespace SiluzzCafe.DesignTokens;");
        sb.AppendLine();
        sb.AppendLine("/// <summary>");
        sb.AppendLine("/// Siluzz Cafe typography design tokens");
        sb.AppendLine("/// </summary>");
        sb.AppendLine("public static class Typography");
        sb.AppendLine("{");

        var typoProperties = typography.GetType().GetProperties();
        foreach (var prop in typoProperties)
        {
            var fontToken = prop.GetValue(typography) as FontToken;
            if (fontToken == null) continue;

            var constantName = ToConstantName(prop.Name);
            
            sb.AppendLine($"    /// <summary>{prop.Name} - {fontToken.FontFamily}, {fontToken.FontSize}, {fontToken.FontWeight}</summary>");
            sb.AppendLine($"    public static readonly FontToken {constantName} = new(");
            sb.AppendLine($"        FontFamily: \"{fontToken.FontFamily}\",");
            sb.AppendLine($"        FontSize: \"{fontToken.FontSize}\",");
            sb.AppendLine($"        FontWeight: \"{fontToken.FontWeight}\",");
            sb.AppendLine($"        LineHeight: \"{fontToken.LineHeight}\",");
            sb.AppendLine($"        LetterSpacing: \"{fontToken.LetterSpacing ?? "normal"}\"");
            sb.AppendLine($"    );");
            sb.AppendLine();
        }

        sb.AppendLine("}");
        sb.AppendLine();
        sb.AppendLine("/// <summary>Font token record</summary>");
        sb.AppendLine("public readonly record struct FontToken(");
        sb.AppendLine("    string FontFamily,");
        sb.AppendLine("    string FontSize,");
        sb.AppendLine("    string FontWeight,");
        sb.AppendLine("    string LineHeight,");
        sb.AppendLine("    string LetterSpacing");
        sb.AppendLine(");");

        return sb.ToString();
    }

    /// <summary>
    /// Generates a C# file with spacing constants
    /// </summary>
    public static string GenerateSpacingConstants(DesignSystem design)
    {
        var spacing = design.Spacing;
        var sb = new System.Text.StringBuilder();

        sb.AppendLine("// <auto-generated />");
        sb.AppendLine($"// Generated from {design.Name} design system");
        sb.AppendLine("#nullable enable");
        sb.AppendLine();
        sb.AppendLine("namespace SiluzzCafe.DesignTokens;");
        sb.AppendLine();
        sb.AppendLine("/// <summary>");
        sb.AppendLine("/// Siluzz Cafe spacing design tokens");
        sb.AppendLine("/// </summary>");
        sb.AppendLine("public static class Spacing");
        sb.AppendLine("{");

        var spacingProperties = spacing.GetType().GetProperties();
        foreach (var prop in spacingProperties)
        {
            var value = prop.GetValue(spacing) as string ?? string.Empty;
            var constantName = ToConstantName(prop.Name);
            
            sb.AppendLine($"    public const string {constantName} = \"{value}\";");
        }

        sb.AppendLine("}");
        return sb.ToString();
    }

    /// <summary>
    /// Generates a C# file with border radius constants
    /// </summary>
    public static string GenerateRoundedConstants(DesignSystem design)
    {
        var rounded = design.Rounded;
        var sb = new System.Text.StringBuilder();

        sb.AppendLine("// <auto-generated />");
        sb.AppendLine($"// Generated from {design.Name} design system");
        sb.AppendLine("#nullable enable");
        sb.AppendLine();
        sb.AppendLine("namespace SiluzzCafe.DesignTokens;");
        sb.AppendLine();
        sb.AppendLine("/// <summary>");
        sb.AppendLine("/// Siluzz Cafe border radius design tokens");
        sb.AppendLine("/// </summary>");
        sb.AppendLine("public static class Rounded");
        sb.AppendLine("{");

        var roundedProperties = rounded.GetType().GetProperties();
        foreach (var prop in roundedProperties)
        {
            var value = prop.GetValue(rounded) as string ?? string.Empty;
            var constantName = ToConstantName(prop.Name);
            
            sb.AppendLine($"    public const string {constantName} = \"{value}\";");
        }

        sb.AppendLine("}");
        return sb.ToString();
    }

    /// <summary>
    /// Generates all token files to a directory
    /// </summary>
    public static void GenerateAll(DesignSystem design, string outputDirectory)
    {
        Directory.CreateDirectory(outputDirectory);

        File.WriteAllText(Path.Combine(outputDirectory, "Colors.cs"), GenerateColorConstants(design));
        File.WriteAllText(Path.Combine(outputDirectory, "Typography.cs"), GenerateTypographyConstants(design));
        File.WriteAllText(Path.Combine(outputDirectory, "Spacing.cs"), GenerateSpacingConstants(design));
        File.WriteAllText(Path.Combine(outputDirectory, "Rounded.cs"), GenerateRoundedConstants(design));

        Console.WriteLine($"Generated design token constants in: {outputDirectory}");
    }

    private static string ToConstantName(string name)
    {
        return string.Concat(name.Split('-', '_').Select(part => 
            char.ToUpperInvariant(part[0]) + part[1..].ToLowerInvariant()));
    }

    private static string GetColorDescription(string colorName)
    {
        return colorName switch
        {
            "primary" => "Fresh chlorophyll green - organic integrity, nutritional balance, health",
            "secondary" => "Zesty carrot-citrus orange - functional CTA engine, add-to-cart, conversion",
            "tertiary" => "Muted sage gray-green - secondary iconography, nutritional category tags",
            "surface" => "Warm canvas background - soft dairy-cream",
            "background" => "Main background - soft warm cream",
            "on-primary" => "Text on primary - white",
            "on-secondary" => "Text on secondary - white",
            "on-surface" => "Text on surface - deep garden charcoal",
            "error" => "Error/destructive actions - muted red",
            _ => colorName
        };
    }
}